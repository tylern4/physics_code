/// Get particle mass from PDG ID
pub fn get_mass(pid: i32) -> f32 {
    match pid {
        2212 | -2212 => MASS_P,
        2112 => MASS_N,
        211 => MASS_PIP,
        -211 => MASS_PIM,
        111 => MASS_PI0,
        321 => MASS_KP,
        -321 => MASS_KM,
        22 => MASS_G,
        11 => MASS_E,
        0 => 0.0,
        _ => 0.0,
    }
}

/// Get particle name from PDG ID
pub fn get_particle_name(pid: i32) -> &'static str {
    match pid {
        2212 => "P",
        -2212 => "-P",
        2112 => "N",
        211 => "PIP",
        -211 => "PIM",
        111 => "PI0",
        321 => "KP",
        -321 => "KM",
        22 => "G",
        11 => "E",
        _ => "UNKNOWN",
    }
}

